"""
Industrial Quality Decision Engine for Multi-Tier Inspection.

Synthesizes telemetry across:
- Tier 1: PatchCore Anomaly Gatekeeper
- Tier 2: Defect Classification (Morphology Categorization)
- Tier 3: Defect Localization (Bounding Boxes & Segmentation Masks)
with calibrated metric dimensions into deterministic operational triage verdicts.

Strict Precedence Hierarchy:
1. FAIL (Precedence 1): High anomaly score exceeding upper margin, or verified critical defect class,
   or calibrated damage area exceeding critical tolerance.
2. REVIEW (Precedence 2): Anomaly score in borderline uncertainty band, or unknown/unmodeled anomaly
   (flagged by Tier 1 but unrecognized by Tier 2/3), or low classifier confidence, or moderate damage.
3. PASS (Precedence 3): Strict nominal verification. Tier 1 anomaly score is safely sub-threshold
   AND zero unmodeled defect components are detected. Sub-threshold damage area can NEVER override
   an anomaly-based FAIL or REVIEW verdict.
"""

from dataclasses import asdict, dataclass, field
from enum import Enum
import logging
from typing import Any, Dict, List, Optional, Set

logger = logging.getLogger(__name__)


class InspectionDecision(str, Enum):
    """Primary operational triage decision for manufactured product."""
    PASS = "PASS"        # Nominal surface meeting quality specifications
    REVIEW = "REVIEW"    # Marginal anomaly or uncertain defect requiring operator confirmation
    FAIL = "FAIL"        # Confirmed defect violating quality specifications; rejected


class SeverityLevel(str, Enum):
    """Categorical severity rating for identified product damage."""
    NONE = "NONE"
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    CRITICAL = "CRITICAL"


class RoutingAction(str, Enum):
    """
    Simulated conveyor routing directive generated by the decision engine.
    NOTE: In production deployment, these software directives are translated into
    hardware actuation signals via industrial PLC/OPC-UA fieldbus interfaces.
    """
    LINE_CONTINUE = "LINE_CONTINUE"                     # Packaging and shipping
    MANUAL_INSPECTION_BAY = "MANUAL_INSPECTION_BAY"     # Operator visual inspection station
    AUTOMATIC_REJECT_BIN = "AUTOMATIC_REJECT_BIN"       # Pneumatic ejection to scrap/recycle chute


@dataclass
class QualityThresholds:
    """
    Configurable tolerance thresholds and rejection limits for industrial quality control.
    NOTE: The default thresholds below are engineering demonstration parameters.
    In factory commissioning, limits must be established by qualified quality engineers
    according to specific product engineering drawings and quality agreements.
    """
    # Operational Anomaly Cutoff:
    # 10.22 = Frozen zero-leakage threshold from calibrate_normal_threshold() on nominal validation
    # 15.50 = Empirical oracle separation midpoint between test normal max (15.37) and defect min (18.10)
    anomaly_threshold: float = 10.22
    anomaly_margin: float = 0.15                   # Uncertainty margin delta (+/- 15%)
    max_acceptable_area_mm2: float = 0.50          # Flaws below this may be tolerated if non-anomalous
    critical_area_mm2: float = 5.00                # Flaws exceeding this trigger automatic rejection
    critical_classes: List[str] = field(default_factory=lambda: [
        "crazing", "broken_large", "deep_crack", "puncture"
    ])
    min_classifier_confidence: float = 0.60        # Lower confidence triggers REVIEW
    max_entropy_threshold: float = 2.0             # Shannon entropy ceiling for classification certainty

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class InspectionVerdict:
    """
    Comprehensive industrial triage verdict synthesizing all vision tiers.
    """
    decision: InspectionDecision
    severity: SeverityLevel
    routing: RoutingAction
    primary_defect_type: str
    confidence: float
    physical_defect_area_mm2: float
    anomaly_score: float
    is_anomalous: bool
    rejection_reasons: List[str] = field(default_factory=list)
    engineering_rationale: str = ""

    def to_dict(self) -> Dict[str, Any]:
        data = asdict(self)
        data["decision"] = self.decision.value
        data["severity"] = self.severity.value
        data["routing"] = self.routing.value
        return data


class DecisionEngine:
    """
    Industrial rule engine evaluating multi-tier optical inspection telemetry
    with strict deterministic precedence.
    """

    def __init__(self, thresholds: Optional[QualityThresholds] = None) -> None:
        self.thresholds = thresholds or QualityThresholds()
        self._critical_classes_set: Set[str] = {c.lower() for c in self.thresholds.critical_classes}

    def evaluate(
        self,
        anomaly_score: float,
        is_anomalous: bool,
        defect_class: Optional[str] = None,
        class_confidence: float = 1.0,
        class_entropy: float = 0.0,
        pixel_defect_area_mm2: float = 0.0,
        bbox_union_area_mm2: float = 0.0,
        num_defect_regions: int = 0
    ) -> InspectionVerdict:
        """
        Synthesizes multi-tier telemetry into an industrial inspection verdict
        following strict precedence: FAIL -> REVIEW -> PASS.

        Args:
            anomaly_score: Continuous score from Tier 1 PatchCore.
            is_anomalous: Flag indicating whether score >= anomaly_threshold.
            defect_class: Predicted defect morphology from Tier 2 classifier.
            class_confidence: Classifier softmax confidence [0.0, 1.0].
            class_entropy: Shannon entropy in bits from Tier 2.
            pixel_defect_area_mm2: Calibrated physical damaged area from segmentation.
            bbox_union_area_mm2: Calibrated physical area of bounding box union.
            num_defect_regions: Number of distinct localized defect regions.

        Returns:
            InspectionVerdict: Structured industrial verdict and routing directive.
        """
        tau = self.thresholds.anomaly_threshold
        delta = self.thresholds.anomaly_margin
        tau_lower = tau * (1.0 - delta)
        tau_upper = tau * (1.0 + delta)

        effective_area_mm2 = max(pixel_defect_area_mm2, 0.0)
        # If segmentation area is 0 but bbox detected substantial defect, use conservative portion of bbox
        if effective_area_mm2 == 0.0 and bbox_union_area_mm2 > 0:
            effective_area_mm2 = bbox_union_area_mm2 * 0.35

        defect_name = (defect_class or "nominal").lower()
        is_nominal_class = defect_name in {"good", "nominal", "none", "normal"}

        fail_reasons: List[str] = []

        # =================================================================
        # PRECEDENCE 1: CRITICAL DEFECT CONDITIONS (AUTOMATIC FAIL)
        # =================================================================
        # 1A. Severe anomaly score exceeding upper confidence margin
        if anomaly_score >= tau_upper:
            fail_reasons.append(
                f"Severe anomaly score ({anomaly_score:.2f}) exceeds upper margin ({tau_upper:.2f})."
            )

        # 1B. Critical defect category identified with sufficient confidence
        if not is_nominal_class and defect_name in self._critical_classes_set:
            if class_confidence >= self.thresholds.min_classifier_confidence:
                fail_reasons.append(
                    f"Critical defect category '{defect_name}' identified with {class_confidence:.1%} confidence."
                )

        # 1C. Calibrated physical damaged area exceeds critical tolerance limit
        if effective_area_mm2 >= self.thresholds.critical_area_mm2:
            fail_reasons.append(
                f"Calibrated physical damaged area ({effective_area_mm2:.2f} mm²) exceeds "
                f"critical limit ({self.thresholds.critical_area_mm2:.2f} mm²)."
            )

        if fail_reasons:
            return InspectionVerdict(
                decision=InspectionDecision.FAIL,
                severity=SeverityLevel.CRITICAL,
                routing=RoutingAction.AUTOMATIC_REJECT_BIN,
                primary_defect_type=defect_name,
                confidence=round(class_confidence, 4),
                physical_defect_area_mm2=round(effective_area_mm2, 3),
                anomaly_score=round(anomaly_score, 4),
                is_anomalous=True,
                rejection_reasons=fail_reasons,
                engineering_rationale=(
                    f"Product REJECTED: {'; '.join(fail_reasons)} "
                    f"Routing command: AUTOMATIC_REJECT_BIN (pneumatic diverter ejection)."
                )
            )

        # =================================================================
        # PRECEDENCE 2: BORDERLINE & UNKNOWN DEFECT CONDITIONS (REVIEW)
        # =================================================================
        review_reasons: List[str] = []

        # 2A. Score in borderline uncertainty margin band [tau_lower, tau_upper]
        if tau_lower <= anomaly_score < tau_upper:
            review_reasons.append(
                f"Anomaly score ({anomaly_score:.2f}) lies in borderline uncertainty band "
                f"[{tau_lower:.2f}, {tau_upper:.2f}]."
            )

        # 2B. Open-Set / Unknown Defect Handling:
        # Tier 1 flagged an anomaly (score >= tau), but supervised models found no known defect
        if (anomaly_score >= tau or is_anomalous) and (is_nominal_class or num_defect_regions == 0):
            review_reasons.append(
                f"Open-set anomaly detected by Tier 1 (score: {anomaly_score:.2f} >= {tau:.2f}) "
                f"unrecognized by supervised defect catalog."
            )

        # 2C. Non-nominal defect identified with area exceeding acceptable tolerance
        if not is_nominal_class and effective_area_mm2 > self.thresholds.max_acceptable_area_mm2:
            review_reasons.append(
                f"Detected defect '{defect_name}' with area {effective_area_mm2:.2f} mm² "
                f"(acceptable limit: {self.thresholds.max_acceptable_area_mm2:.2f} mm²)."
            )

        # 2D. High classifier uncertainty on an identified defect
        if not is_nominal_class and (
            class_confidence < self.thresholds.min_classifier_confidence or
            class_entropy > self.thresholds.max_entropy_threshold
        ):
            review_reasons.append(
                f"Classifier uncertainty elevated (confidence: {class_confidence:.1%}, "
                f"entropy: {class_entropy:.2f} bits)."
            )

        if review_reasons:
            severity = SeverityLevel.MEDIUM if effective_area_mm2 > 1.0 or anomaly_score >= tau else SeverityLevel.LOW
            return InspectionVerdict(
                decision=InspectionDecision.REVIEW,
                severity=severity,
                routing=RoutingAction.MANUAL_INSPECTION_BAY,
                primary_defect_type=defect_name if not is_nominal_class else "unmodeled_anomaly",
                confidence=round(class_confidence, 4),
                physical_defect_area_mm2=round(effective_area_mm2, 3),
                anomaly_score=round(anomaly_score, 4),
                is_anomalous=is_anomalous or (anomaly_score >= tau),
                rejection_reasons=review_reasons,
                engineering_rationale=(
                    f"Diverted for OPERATOR REVIEW: {'; '.join(review_reasons)} "
                    f"Routing command: MANUAL_INSPECTION_BAY (secondary QA station)."
                )
            )

        # =================================================================
        # PRECEDENCE 3: STRICT NOMINAL ACCEPTANCE (PASS)
        # =================================================================
        # PASS requires that Tier 1 anomaly score is safely sub-threshold (< tau_lower)
        # AND no unmodeled anomaly is present.
        if anomaly_score >= tau_lower or is_anomalous:
            # Fallback guard: if any anomaly flag survived, force REVIEW
            return InspectionVerdict(
                decision=InspectionDecision.REVIEW,
                severity=SeverityLevel.LOW,
                routing=RoutingAction.MANUAL_INSPECTION_BAY,
                primary_defect_type=defect_name if not is_nominal_class else "marginal_variance",
                confidence=round(class_confidence, 4),
                physical_defect_area_mm2=round(effective_area_mm2, 3),
                anomaly_score=round(anomaly_score, 4),
                is_anomalous=is_anomalous,
                rejection_reasons=[f"Anomaly score ({anomaly_score:.2f}) exceeds lower safety margin ({tau_lower:.2f})."],
                engineering_rationale="Borderline safety margin breach; routed for visual review."
            )

        # Check for minor non-critical superficial blemish within acceptable tolerance
        if effective_area_mm2 > 0 and effective_area_mm2 <= self.thresholds.max_acceptable_area_mm2 and not is_nominal_class:
            return InspectionVerdict(
                decision=InspectionDecision.PASS,
                severity=SeverityLevel.LOW,
                routing=RoutingAction.LINE_CONTINUE,
                primary_defect_type=defect_name,
                confidence=round(class_confidence, 4),
                physical_defect_area_mm2=round(effective_area_mm2, 3),
                anomaly_score=round(anomaly_score, 4),
                is_anomalous=False,
                rejection_reasons=[],
                engineering_rationale=(
                    f"Product PASSED: Minor superficial blemish '{defect_name}' ({effective_area_mm2:.2f} mm²) "
                    f"is within acceptable quality tolerance ({self.thresholds.max_acceptable_area_mm2:.2f} mm²). "
                    f"Anomaly score {anomaly_score:.2f} is safely nominal."
                )
            )

        # Standard clean nominal product
        return InspectionVerdict(
            decision=InspectionDecision.PASS,
            severity=SeverityLevel.NONE,
            routing=RoutingAction.LINE_CONTINUE,
            primary_defect_type="nominal",
            confidence=round(1.0 - (anomaly_score / tau), 4) if tau > 0 else 1.0,
            physical_defect_area_mm2=0.0,
            anomaly_score=round(anomaly_score, 4),
            is_anomalous=False,
            rejection_reasons=[],
            engineering_rationale=(
                f"Tier 1 Gatekeeper PASSED: Anomaly score {anomaly_score:.2f} is well below "
                f"threshold {tau:.2f} (safety margin {tau_lower:.2f}). Clean nominal surface."
            )
        )
